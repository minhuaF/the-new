#!/bin/bash

# ==========================================
# 停止开发环境脚本
# ==========================================
# 功能：停止 Supabase 本地服务
# ==========================================

set -e

# 颜色输出
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}===========================================${NC}"
echo -e "${BLUE}🛑 停止开发环境${NC}"
echo -e "${BLUE}===========================================${NC}"

# 停止 Supabase
echo -e "\n${YELLOW}停止 Supabase 服务...${NC}"
if supabase stop; then
  echo -e "${GREEN}✓ Supabase 已停止${NC}"
else
  echo -e "${RED}✗ Supabase 停止失败${NC}"
  exit 1
fi

echo -e "\n${BLUE}===========================================${NC}"
echo -e "${GREEN}✓ 开发环境已停止${NC}"
echo -e "${BLUE}===========================================${NC}\n"
